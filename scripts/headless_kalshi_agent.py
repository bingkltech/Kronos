@dataclass
class KalshiMarketContract:
    """Specification of an active Kalshi binary prediction contract."""
    ticker: str                 # e.g., "KXBTCD-26OCT25-83000"
    title: str                  # e.g., "Will Bitcoin close above $83,000 at 5:00 PM?"
    underlying_symbol: str      # e.g., "BTCUSDT"
    strike_price: Decimal       # Target strike price K (e.g., Decimal("83000.00"))
    expiry_horizon_steps: int   # Number of future candles until settlement (e.g., 6 hours = 6)
    yes_ask: Decimal            # Current lowest ask to Buy YES (e.g., Decimal("0.44"))
    no_ask: Decimal             # Current lowest ask to Buy NO  (e.g., Decimal("0.58"))
    settlement_payout: Decimal = Decimal("1.00")  # Kalshi contracts pay $1.00 upon winning


@dataclass
class KalshiDecision:
    """Actionable decision output generated by Kronos for an event contract."""
    ticker: str
    action: str                 # "BUY_YES", "BUY_NO", or "PASS"
    strike_price: Decimal
    spot_price: Decimal
    forecasted_terminal: Decimal
    forecasted_return_pct: Decimal
    model_prob_yes: Decimal
    market_prob_yes: Decimal
    edge: Decimal
    expected_value: Decimal
    recommended_contracts: int
    capital_at_risk: Decimal
    max_payout: Decimal
    kelly_fraction: Decimal
    rationale: str

    def to_dict(self) -> Dict[str, Union[str, int]]:
        """Serialize cleanly to JSON-compatible dictionary."""
        return {
            "ticker": self.ticker,
            "action": self.action,
            "strike_price": str(self.strike_price),
            "spot_price": str(self.spot_price),
            "forecasted_terminal": str(self.forecasted_terminal),
            "forecasted_return_pct": f"{self.forecasted_return_pct:+.2f}%",
            "model_prob_yes": f"{self.model_prob_yes:.4f}",
            "market_prob_yes": f"{self.market_prob_yes:.4f}",
            "edge": f"{self.edge:+.4f}",
            "expected_value_usd": f"${self.expected_value:+.4f}",
            "recommended_contracts": self.recommended_contracts,
            "capital_at_risk_usd": f"${self.capital_at_risk:.2f}",
            "max_payout_usd": f"${self.max_payout:.2f}",
            "kelly_fraction": f"{self.kelly_fraction:.4f}",
            "rationale": self.rationale
        }


