def run_headless_simulation(mode: str = "rest", data_file: str = "data/binance_BTCUSDT_1h.csv"):
    """
    Demonstrates headless evaluation on simulated Kalshi event contracts.
    """
    print("=" * 80)
    print(" KRONOS QUANT FOUNDATION — HEADLESS KALSHI DECISION ENGINE")
    print(f" Mode: {mode.upper()} | Base Checkpoint: NeoQuasar/Kronos-base (102.3M)")
    print("=" * 80)

    # 1. Load historical lookback data
    csv_path = os.path.join(WORKSPACE_ROOT, data_file)
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Historical lookback dataset not found at {csv_path}")

    df = pd.read_csv(csv_path)
    df['timestamps'] = pd.to_datetime(df['timestamps'])
    # Strict tail slicing contract: take latest 400 candles
    lookback_df = df.iloc[-400:].copy()
    current_spot = Decimal(str(lookback_df['close'].iloc[-1]))

    print(f"Loaded {len(lookback_df)} historical lookback candles from {data_file}.")
    print(f"Current Underlying Spot Price (BTC): ${current_spot:,.2f}\n")

    # 2. Initialize Backend
    if mode == "sdk":
        backend = DirectSDKBackend(model_id="NeoQuasar/Kronos-base", tokenizer_id="NeoQuasar/Kronos-Tokenizer-base")
    else:
        backend = RESTClientBackend(endpoint_url="http://localhost:7070")

    engine = KalshiDecisionEngine(
        backend=backend,
        min_edge_cents=Decimal("0.05"),   # 5c edge threshold
        kelly_fraction=Decimal("0.25"),  # Quarter-Kelly
        max_bankroll_pct=Decimal("0.10") # Max 10% allocation
    )

    # 3. Define 3 Realistic Kalshi Contracts Around Current Spot
    # Strike 1: Realistic Bullish Target (Spot + 0.8%)
    # Strike 2: Realistic Bearish Target (Spot + 3.0%, unlikely in short horizon)
    # Strike 3: Tight Spread At-The-Money (Efficient market, testing PASS logic)
    contracts = [
        KalshiMarketContract(
            ticker="KXBTCD-TODAY-BULL",
            title="Will BTC close above Spot + 0.8% in 6 hours?",
            underlying_symbol="BTCUSDT",
            strike_price=(current_spot * Decimal("1.008")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            expiry_horizon_steps=6,
            yes_ask=Decimal("0.42"),  # Market gives 42% chance
            no_ask=Decimal("0.61")
        ),
        KalshiMarketContract(
            ticker="KXBTCD-TODAY-FAR",
            title="Will BTC close above Spot + 3.0% in 6 hours?",
            underlying_symbol="BTCUSDT",
            strike_price=(current_spot * Decimal("1.030")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            expiry_horizon_steps=6,
            yes_ask=Decimal("0.35"),  # Market overpricing YES
            no_ask=Decimal("0.68")   # Market gives NO at 68c
        ),
        KalshiMarketContract(
            ticker="KXBTCD-TODAY-ATM",
            title="Will BTC close above Spot + 0.05% in 6 hours?",
            underlying_symbol="BTCUSDT",
            strike_price=(current_spot * Decimal("1.0005")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            expiry_horizon_steps=6,
            yes_ask=Decimal("0.51"),
            no_ask=Decimal("0.52")
        )
    ]

    bankroll = Decimal("5000.00")
    print(f"Simulating Decision Engine across {len(contracts)} Kalshi Contracts (Bankroll: ${bankroll:,.2f}):\n")

    results = engine.evaluate_contracts_batch(contracts, lookback_df, bankroll=bankroll)

    for c, decision in zip(contracts, results):
        action_badge = f"[{decision.action}]"
        print(f" Contract: {c.ticker} ({c.title})")
        print(f" -> Strike: ${c.strike_price:,.2f} | Forecast Terminal: ${decision.forecasted_terminal:,.2f} ({decision.forecasted_return_pct:+.2f}%)")
        print(f" -> Decision: {action_badge:<10} | Model P(YES): {decision.model_prob_yes*Decimal('100'):.1f}% | Market Ask: {c.yes_ask*Decimal('100'):.1f}c")
        print(f" -> Edge: {decision.edge*Decimal('100'):+.1f}c | Expected Value: ${decision.expected_value:+.2f}")
        print(f" -> Size: {decision.recommended_contracts} contracts | Capital At Risk: ${decision.capital_at_risk:.2f} | Max Payout: ${decision.max_payout:.2f}")
        print(f" -> Rationale: {decision.rationale}\n")

    # Output structured JSON summary for programmatic consumption
    json_output = [r.to_dict() for r in results]
    print("-" * 80)
    print("HEADLESS JSON IPC OUTPUT (Ready for external bots / Kalshi API dispatch):")
    print(json.dumps(json_output, indent=2))
    print("-" * 80)


