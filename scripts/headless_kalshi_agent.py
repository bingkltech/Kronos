class BaseKronosBackend:
    """Abstract interface for headless Kronos forecasting."""
    def predict_horizon(self, lookback_df: pd.DataFrame, pred_len: int) -> pd.DataFrame:
        raise NotImplementedError


class DirectSDKBackend(BaseKronosBackend):
    """
    Direct in-process PyTorch SDK inference backend.
    Fastest execution, zero network overhead, supports GPU or CPU.
    """
    def __init__(self, model_id: str = "NeoQuasar/Kronos-base", tokenizer_id: str = "NeoQuasar/Kronos-Tokenizer-base", device: Optional[str] = None):
        import torch
        from model import Kronos, KronosTokenizer, KronosPredictor

        self.device = device or ("cuda:0" if torch.cuda.is_available() else "cpu")
        print(f"[SDKBackend] Initializing Kronos Predictor ({model_id}) on {self.device}...")
        self.tokenizer = KronosTokenizer.from_pretrained(tokenizer_id)
        self.model = Kronos.from_pretrained(model_id)
        self.predictor = KronosPredictor(self.model, self.tokenizer, device=self.device, max_context=512)
        print("[SDKBackend] Kronos Predictor successfully loaded in-memory.")

    def predict_horizon(self, lookback_df: pd.DataFrame, pred_len: int) -> pd.DataFrame:
        # Enforce context slicing contract: tail slice <= 512 bars
        sliced_df = lookback_df.iloc[-512:].copy()
        required_cols = ['open', 'high', 'low', 'close']
        if 'volume' in sliced_df.columns:
            required_cols.append('volume')

        x_df = sliced_df[required_cols]
        x_timestamp = sliced_df['timestamps']

        # Construct future timestamps
        if len(x_timestamp) > 1:
            step_delta = x_timestamp.iloc[-1] - x_timestamp.iloc[-2]
        else:
            step_delta = pd.Timedelta(hours=1)
        y_timestamp = pd.date_range(start=x_timestamp.iloc[-1] + step_delta, periods=pred_len, freq=step_delta)

        # Autoregressive inference
        pred_df = self.predictor.predict(
            df=x_df,
            x_timestamp=x_timestamp,
            y_timestamp=y_timestamp,
            pred_len=pred_len,
            T=1.0,
            top_p=0.9,
            sample_count=1,
            verbose=False
        )
        return pred_df


class RESTClientBackend(BaseKronosBackend):
    """
    Decoupled REST API backend calling a running Kronos microservice (e.g. WebUI on port 7070).
    Allows external bots in any language/runtime to query Kronos without installing PyTorch.
    """
    def __init__(self, endpoint_url: str = "http://localhost:7070"):
        import requests
        self.endpoint_url = endpoint_url.rstrip("/")
        self.requests = requests
        self._ensure_server_ready()

    def _ensure_server_ready(self):
        try:
            status_resp = self.requests.get(f"{self.endpoint_url}/api/model-status", timeout=5)
            status_data = status_resp.json()
            if not status_data.get("loaded", False):
                print(f"[RESTBackend] Server online but model not loaded. Sending /api/load-model for kronos-base...")
                load_resp = self.requests.post(
                    f"{self.endpoint_url}/api/load-model",
                    json={"model_key": "kronos-base", "device": "cpu"},
                    timeout=30
                )
                if not load_resp.json().get("success", False):
                    raise RuntimeError(f"Failed to load model via REST: {load_resp.text}")
            print(f"[RESTBackend] Connected to Kronos microservice at {self.endpoint_url}.")
        except Exception as e:
            raise ConnectionError(f"Cannot reach Kronos microservice at {self.endpoint_url}: {e}")

    def predict_horizon(self, lookback_df: pd.DataFrame, pred_len: int) -> pd.DataFrame:
        # Enforce context slicing contract: tail slice
        sliced_df = lookback_df.iloc[-512:].copy()
        
        # Save temporary lookback CSV for API ingestion
        temp_dir = os.path.join(WORKSPACE_ROOT, "data")
        os.makedirs(temp_dir, exist_ok=True)
        temp_csv = os.path.join(temp_dir, "_temp_headless_lookback.csv")
        sliced_df.to_csv(temp_csv, index=False)

        payload = {
            "file_path": temp_csv,
            "lookback": min(400, len(sliced_df)),
            "pred_len": pred_len,
            "use_tail": True,
            "temperature": 1.0,
            "top_p": 0.9,
            "sample_count": 1
        }
        resp = self.requests.post(f"{self.endpoint_url}/api/predict", json=payload, timeout=120)
        resp_data = resp.json()
        if not resp_data.get("success", False):
            raise RuntimeError(f"REST prediction failed: {resp_data.get('error')}")

        pred_rows = resp_data["prediction_results"]
        pred_df = pd.DataFrame(pred_rows)
        return pred_df


