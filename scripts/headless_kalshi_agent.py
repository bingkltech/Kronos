class KalshiDecisionEngine:
    """
    Quant Decision Engine integrating Kronos forecasts with binary event contract pricing.
    Computes model probability, market edge, expected value, and Fractional Kelly contract sizing.
    """
    def __init__(
        self,
        backend: BaseKronosBackend,
        min_edge_cents: Decimal = Decimal("0.05"),      # Minimum 5c edge required to execute
        kelly_fraction: Decimal = Decimal("0.25"),     # Quarter-Kelly for risk conservation
        max_bankroll_pct: Decimal = Decimal("0.10")    # Max 10% of total bankroll per position
    ):
        self.backend = backend
        self.min_edge_cents = min_edge_cents
        self.kelly_fraction = kelly_fraction
        self.max_bankroll_pct = max_bankroll_pct

    def evaluate_contract(
        self,
        contract: KalshiMarketContract,
        lookback_df: pd.DataFrame,
        bankroll: Decimal = Decimal("1000.00"),
        pred_df: Optional[pd.DataFrame] = None
    ) -> KalshiDecision:
        """
        Evaluate a single Kalshi binary contract against Kronos future trajectory.
        All monetary and contract sizing calculations are executed in exact Decimal.
        """
        # 1. Enforce strict tail slicing contract
        tail_df = lookback_df.iloc[-512:].copy()
        current_spot = Decimal(str(tail_df['close'].iloc[-1]))

        # 2. Forecast future path up to expiry horizon (or use cached forecast)
        if pred_df is None:
            pred_df = self.backend.predict_horizon(tail_df, contract.expiry_horizon_steps)
        else:
            pred_df = pred_df.iloc[:contract.expiry_horizon_steps].copy()

        terminal_close = Decimal(str(round(float(pred_df['close'].iloc[-1]), 2)))
        
        # Calculate forecasted return percentage
        return_pct = ((terminal_close - current_spot) / current_spot) * Decimal("100")

        # 3. Model Probability Formulation
        # In a binary contract, YES wins if S_T >= K.
        # We estimate subjective probability using projected drift and path volatility.
        high_vals = [float(x) for x in pred_df['high'].values]
        low_vals = [float(x) for x in pred_df['low'].values]
        path_std = float(np.std(pred_df['close'].values)) + 1e-4
        
        # Standardized distance from strike in volatility units (Z-score)
        z = (float(terminal_close) - float(contract.strike_price)) / (path_std * math.sqrt(max(1, contract.expiry_horizon_steps)))
        # Standard normal CDF approximation
        prob_yes_raw = 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))
        # Bounded between 0.02 and 0.98 to avoid overconfidence
        prob_yes_clamped = max(0.02, min(0.98, prob_yes_raw))
        p_yes_model = Decimal(str(round(prob_yes_clamped, 4)))
        p_no_model = Decimal("1.0000") - p_yes_model

        # 4. Market Prices and Implied Probabilities
        market_p_yes = contract.yes_ask
        market_p_no = contract.no_ask

        # 5. Expected Value (EV) & Edge Calculation
        # Payout is $1.00. Cost is ask price.
        # EV(YES) = p_yes * $1.00 - yes_ask
        # EV(NO)  = (1 - p_yes) * $1.00 - no_ask
        ev_yes = (p_yes_model * contract.settlement_payout) - market_p_yes
        ev_no = (p_no_model * contract.settlement_payout) - market_p_no

        edge_yes = p_yes_model - market_p_yes
        edge_no = p_no_model - market_p_no

        # 6. Directional Decision Logic
        action = "PASS"
        chosen_edge = Decimal("0.0")
        chosen_ev = Decimal("0.0")
        contract_cost = Decimal("1.00")
        win_prob = Decimal("0.50")

        if ev_yes >= self.min_edge_cents and edge_yes > Decimal("0"):
            action = "BUY_YES"
            chosen_edge = edge_yes
            chosen_ev = ev_yes
            contract_cost = market_p_yes
            win_prob = p_yes_model
        elif ev_no >= self.min_edge_cents and edge_no > Decimal("0"):
            action = "BUY_NO"
            chosen_edge = edge_no
            chosen_ev = ev_no
            contract_cost = market_p_no
            win_prob = p_no_model
        else:
            action = "PASS"
            chosen_edge = max(edge_yes, edge_no)
            chosen_ev = max(ev_yes, ev_no)

        # 7. Kelly Criterion Contract Sizing (Zero Float Math)
        # Full Kelly: f* = (b*p - q) / b, where b = (payout - cost) / cost
        recommended_contracts = 0
        capital_at_risk = Decimal("0.00")
        max_payout = Decimal("0.00")
        kelly_fraction_used = Decimal("0.00")

        if action != "PASS" and contract_cost > Decimal("0"):
            b = (contract.settlement_payout - contract_cost) / contract_cost
            q = Decimal("1.00") - win_prob
            full_kelly = ((b * win_prob) - q) / b

            if full_kelly > Decimal("0"):
                # Apply fractional Kelly scaling (Quarter-Kelly)
                scaled_kelly = full_kelly * self.kelly_fraction
                # Cap at max bankroll allocation limit
                scaled_kelly = min(scaled_kelly, self.max_bankroll_pct)
                kelly_fraction_used = scaled_kelly

                allocated_capital = bankroll * scaled_kelly
                # Compute integer contracts (rounded down)
                raw_contracts = allocated_capital / contract_cost
                recommended_contracts = int(raw_contracts.quantize(Decimal("1"), rounding=ROUND_DOWN))
                
                capital_at_risk = (Decimal(str(recommended_contracts)) * contract_cost).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
                max_payout = (Decimal(str(recommended_contracts)) * contract.settlement_payout).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

        # 8. Human-Readable Rationale
        if action == "BUY_YES":
            rationale = (
                f"Kronos forecasts terminal {contract.underlying_symbol} at ${terminal_close} ({return_pct:+.2f}%) "
                f"exceeding strike ${contract.strike_price}. Model assigns {p_yes_model*Decimal('100'):.1f}% YES probability "
                f"vs market ask of {market_p_yes*Decimal('100'):.1f}c (+{chosen_edge*Decimal('100'):.1f}c edge, EV=${chosen_ev:+.2f}). "
                f"Sized at {recommended_contracts} contracts via Quarter-Kelly."
            )
        elif action == "BUY_NO":
            rationale = (
                f"Kronos forecasts terminal {contract.underlying_symbol} at ${terminal_close} ({return_pct:+.2f}%) "
                f"staying below strike ${contract.strike_price}. Model assigns {p_no_model*Decimal('100'):.1f}% NO probability "
                f"vs market ask of {market_p_no*Decimal('100'):.1f}c (+{chosen_edge*Decimal('100'):.1f}c edge, EV=${chosen_ev:+.2f}). "
                f"Sized at {recommended_contracts} contracts via Quarter-Kelly."
            )
        else:
            rationale = (
                f"Kronos forecasts terminal {contract.underlying_symbol} at ${terminal_close} ({return_pct:+.2f}%). "
                f"Neither YES (edge: {edge_yes*Decimal('100'):+.1f}c) nor NO (edge: {edge_no*Decimal('100'):+.1f}c) "
                f"meets the minimum hurdle edge of {self.min_edge_cents*Decimal('100'):.0f}c. Capital preserved."
            )

        return KalshiDecision(
            ticker=contract.ticker,
            action=action,
            strike_price=contract.strike_price,
            spot_price=current_spot,
            forecasted_terminal=terminal_close,
            forecasted_return_pct=return_pct,
            model_prob_yes=p_yes_model,
            market_prob_yes=market_p_yes,
            edge=chosen_edge,
            expected_value=chosen_ev,
            recommended_contracts=recommended_contracts,
            capital_at_risk=capital_at_risk,
            max_payout=max_payout,
            kelly_fraction=kelly_fraction_used,
            rationale=rationale
        )

    def evaluate_contracts_batch(
        self,
        contracts: List[KalshiMarketContract],
        lookback_df: pd.DataFrame,
        bankroll: Decimal = Decimal("1000.00")
    ) -> List[KalshiDecision]:
        """
        Evaluate multiple contracts for the same underlying asset efficiently by
        generating Kronos forecast once up to max horizon and slicing for each contract.
        """
        if not contracts:
            return []
        tail_df = lookback_df.iloc[-512:].copy()
        max_horizon = max(c.expiry_horizon_steps for c in contracts)
        print(f"[Engine] Generating single Kronos forecast trajectory for horizon={max_horizon} steps...")
        pred_df = self.backend.predict_horizon(tail_df, max_horizon)
        print(f"[Engine] Forecast trajectory ready. Evaluating {len(contracts)} contracts...")
        return [
            self.evaluate_contract(c, tail_df, bankroll=bankroll, pred_df=pred_df)
            for c in contracts
        ]


