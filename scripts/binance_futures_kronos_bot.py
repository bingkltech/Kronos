class BinanceFuturesDataClient:
    """Direct, public client for Binance USD(S)-M Futures market data."""
    BASE_URL = "https://fapi.binance.com"

    def __init__(self, timeout: int = 15):
        self.timeout = timeout
        self.session = requests.Session()
        self.session.headers.update({"User-Agent": "Kronos-Quant-Futures-Bot/1.0"})

    def fetch_klines(self, symbol: str = "BTCUSDT", interval: str = "1h", limit: int = 500) -> pd.DataFrame:
        """
        Fetch historical candlestick bars from Binance USD(S)-M Futures.
        Returns cleaned DataFrame with verified OHLCV columns and datetime timestamps.
        """
        endpoint = f"{self.BASE_URL}/fapi/v1/klines"
        params = {
            "symbol": symbol.upper().strip(),
            "interval": interval,
            "limit": min(1000, limit)
        }
        resp = self.session.get(endpoint, params=params, timeout=self.timeout)
        resp.raise_for_status()
        raw_klines = resp.json()

        records = []
        for row in raw_klines:
            records.append({
                "timestamps": pd.to_datetime(row[0], unit='ms'),
                "open": float(row[1]),
                "high": float(row[2]),
                "low": float(row[3]),
                "close": float(row[4]),
                "volume": float(row[5]),
                "amount": float(row[7])
            })

        df = pd.DataFrame(records)
        df = df.sort_values("timestamps").reset_index(drop=True)
        return df


