class KronosFuturesStrategy:
    """
    Quant strategy engine translating Kronos autoregressive trajectory forecasts
    into risk-managed Binance Futures trade specifications.
    """
    def __init__(
        self,
        api_url: str = "http://localhost:7070",
        min_hurdle_pct: Decimal = Decimal("0.0060"),      # Minimum 0.60% expected drift after fees
        max_risk_per_trade_pct: Decimal = Decimal("0.015"), # Risk 1.5% of equity per trade
        max_leverage: int = 5,                            # Max 5x leverage for risk preservation
        min_risk_reward: Decimal = Decimal("1.50")        # Require at least 1.5:1 Risk/Reward
    ):
        self.api_url = api_url.rstrip("/")
        self.min_hurdle_pct = min_hurdle_pct
        self.max_risk_per_trade_pct = max_risk_per_trade_pct
        self.max_leverage = max_leverage
        self.min_risk_reward = min_risk_reward

    def generate_forecast(self, lookback_df: pd.DataFrame, pred_len: int = 12) -> pd.DataFrame:
        """Query Kronos microservice for future trajectory (tail-sliced <= 512 bars)."""
        # Strict context slicing contract
        tail_df = lookback_df.iloc[-400:].copy()
        temp_csv = os.path.join(WORKSPACE_ROOT, "data", "_temp_futures_lookback.csv")
        tail_df.to_csv(temp_csv, index=False)

        payload = {
            "file_path": temp_csv,
            "lookback": len(tail_df),
            "pred_len": pred_len,
            "use_tail": True,
            "temperature": 1.0,
            "top_p": 0.9,
            "sample_count": 1
        }
        resp = requests.post(f"{self.api_url}/api/predict", json=payload, timeout=120)
        resp_data = resp.json()
        if not resp_data.get("success", False):
            raise RuntimeError(f"Kronos prediction failed: {resp_data.get('error')}")

        return pd.DataFrame(resp_data["prediction_results"])

    def evaluate_market(
        self,
        symbol_config: FuturesSymbolConfig,
        lookback_df: pd.DataFrame,
        account_equity: Decimal = Decimal("10000.00"),
        horizon_hours: int = 12
    ) -> FuturesTradeSignal:
        """
        Evaluate market lookback and construct an institutional trade bracket.
        All pricing, sizing, fee deductions, and margin calculations are strictly Decimal.
        """
        tail_df = lookback_df.iloc[-512:].copy()
        spot_price = Decimal(str(tail_df['close'].iloc[-1]))

        # 1. Run Kronos inference
        pred_df = self.generate_forecast(tail_df, pred_len=horizon_hours)

        terminal_close = Decimal(str(round(float(pred_df['close'].iloc[-1]), symbol_config.price_precision)))
        path_high = Decimal(str(round(float(pred_df['high'].max()), symbol_config.price_precision)))
        path_low = Decimal(str(round(float(pred_df['low'].min()), symbol_config.price_precision)))

        # 2. Raw drift & round-trip friction calculation
        raw_drift = (terminal_close - spot_price) / spot_price
        roundtrip_fee_rate = (symbol_config.taker_fee_rate * Decimal("2")) + (symbol_config.est_slippage_rate * Decimal("2"))
        net_drift = abs(raw_drift) - roundtrip_fee_rate

        # 3. Decision Logic & Bracket Construction
        direction = "NEUTRAL"
        entry_price = spot_price
        stop_loss = spot_price
        take_profit = spot_price
        rationale = ""

        # Long Setup: Positive drift exceeding fee hurdle
        if raw_drift > Decimal("0") and net_drift >= self.min_hurdle_pct:
            # Dynamic Stop Loss based on forecast envelope (or 1.2% ATR safety ceiling)
            candidate_sl = min(path_low, spot_price * Decimal("0.988"))
            candidate_tp = max(path_high, terminal_close)

            risk_dist = (spot_price - candidate_sl) / spot_price
            reward_dist = (candidate_tp - spot_price) / spot_price
            rr = (reward_dist / risk_dist) if risk_dist > Decimal("0") else Decimal("0")

            if rr >= self.min_risk_reward and risk_dist > Decimal("0.003"):
                direction = "LONG"
                stop_loss = candidate_sl.quantize(Decimal(f"1e-{symbol_config.price_precision}"), rounding=ROUND_HALF_UP)
                take_profit = candidate_tp.quantize(Decimal(f"1e-{symbol_config.price_precision}"), rounding=ROUND_HALF_UP)
                rationale = (
                    f"Kronos forecasts {symbol_config.symbol} bullish drift to ${terminal_close:,.2f} ({raw_drift*Decimal('100'):+.2f}%). "
                    f"Net drift after 0.16% round-trip friction is {net_drift*Decimal('100'):+.2f}% (>= {self.min_hurdle_pct*Decimal('100'):.2f}% hurdle). "
                    f"Risk/Reward: {rr:.2f}:1."
                )

        # Short Setup: Negative drift exceeding fee hurdle
        elif raw_drift < Decimal("0") and net_drift >= self.min_hurdle_pct:
            candidate_sl = max(path_high, spot_price * Decimal("1.012"))
            candidate_tp = min(path_low, terminal_close)

            risk_dist = (candidate_sl - spot_price) / spot_price
            reward_dist = (spot_price - candidate_tp) / spot_price
            rr = (reward_dist / risk_dist) if risk_dist > Decimal("0") else Decimal("0")

            if rr >= self.min_risk_reward and risk_dist > Decimal("0.003"):
                direction = "SHORT"
                stop_loss = candidate_sl.quantize(Decimal(f"1e-{symbol_config.price_precision}"), rounding=ROUND_HALF_UP)
                take_profit = candidate_tp.quantize(Decimal(f"1e-{symbol_config.price_precision}"), rounding=ROUND_HALF_UP)
                rationale = (
                    f"Kronos forecasts {symbol_config.symbol} bearish drift to ${terminal_close:,.2f} ({raw_drift*Decimal('100'):+.2f}%). "
                    f"Net drift after 0.16% round-trip friction is {net_drift*Decimal('100'):+.2f}% (>= {self.min_hurdle_pct*Decimal('100'):.2f}% hurdle). "
                    f"Risk/Reward: {rr:.2f}:1."
                )

        if direction == "NEUTRAL":
            rationale = (
                f"Kronos drift of {raw_drift*Decimal('100'):+.2f}% does not exceed minimum net fee hurdle of "
                f"{self.min_hurdle_pct*Decimal('100'):.2f}% or violates min 1.5:1 Risk/Reward. Capital preserved."
            )
            return FuturesTradeSignal(
                symbol=symbol_config.symbol,
                direction="NEUTRAL",
                spot_price=spot_price,
                forecasted_terminal=terminal_close,
                forecasted_return_pct=raw_drift * Decimal("100"),
                entry_price=spot_price,
                stop_loss=spot_price,
                take_profit=spot_price,
                risk_distance_pct=Decimal("0.00"),
                reward_distance_pct=Decimal("0.00"),
                risk_reward_ratio=Decimal("0.00"),
                recommended_leverage=1,
                position_quantity=Decimal("0.00"),
                notional_value_usd=Decimal("0.00"),
                margin_required_usd=Decimal("0.00"),
                capital_at_risk_usd=Decimal("0.00"),
                est_roundtrip_fee_usd=Decimal("0.00"),
                net_expected_profit_usd=Decimal("0.00"),
                rationale=rationale
            )

        # 4. Decimal Risk-Budgeted Position Sizing
        # Dollar risk = Account Equity * Max Risk %
        dollar_risk_budget = account_equity * self.max_risk_per_trade_pct
        risk_per_unit = abs(entry_price - stop_loss)
        
        raw_quantity = dollar_risk_budget / risk_per_unit
        # Quantize to symbol step size
        qty_step = Decimal(f"1e-{symbol_config.quantity_precision}")
        position_quantity = max(symbol_config.min_quantity, raw_quantity.quantize(qty_step, rounding=ROUND_DOWN))

        notional_value = (position_quantity * entry_price).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
        capital_at_risk = (position_quantity * risk_per_unit).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

        # Leverage determination: cap leverage strictly at safety limit
        raw_leverage = int((notional_value / account_equity).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
        recommended_leverage = max(1, min(self.max_leverage, raw_leverage if raw_leverage > 0 else 1))

        margin_required = (notional_value / Decimal(str(recommended_leverage))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
        est_roundtrip_fee = (notional_value * roundtrip_fee_rate).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

        gross_expected_profit = position_quantity * abs(take_profit - entry_price)
        net_expected_profit = (gross_expected_profit - est_roundtrip_fee).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)

        return FuturesTradeSignal(
            symbol=symbol_config.symbol,
            direction=direction,
            spot_price=spot_price,
            forecasted_terminal=terminal_close,
            forecasted_return_pct=(raw_drift * Decimal("100")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            entry_price=entry_price,
            stop_loss=stop_loss,
            take_profit=take_profit,
            risk_distance_pct=((abs(entry_price - stop_loss) / entry_price) * Decimal("100")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            reward_distance_pct=((abs(take_profit - entry_price) / entry_price) * Decimal("100")).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            risk_reward_ratio=rr.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP),
            recommended_leverage=recommended_leverage,
            position_quantity=position_quantity,
            notional_value_usd=notional_value,
            margin_required_usd=margin_required,
            capital_at_risk_usd=capital_at_risk,
            est_roundtrip_fee_usd=est_roundtrip_fee,
            net_expected_profit_usd=net_expected_profit,
            rationale=rationale
        )


