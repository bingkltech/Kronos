@dataclass
class FuturesSymbolConfig:
    """Trading parameters for a Binance USD(S)-M Futures contract."""
    symbol: str               # e.g. "BTCUSDT"
    price_precision: int      # e.g. 2 decimals
    quantity_precision: int   # e.g. 3 decimals (stepSize: 0.001)
    min_quantity: Decimal     # e.g. Decimal("0.001")
    taker_fee_rate: Decimal = Decimal("0.0005")   # 0.05% standard VIP0 taker fee
    maker_fee_rate: Decimal = Decimal("0.0002")   # 0.02% standard VIP0 maker fee
    est_slippage_rate: Decimal = Decimal("0.0003") # 0.03% estimated execution slippage


