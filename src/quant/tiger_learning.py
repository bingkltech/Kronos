def classify_trade_autopsy(
    is_win: bool,
    mfe_pct: Decimal,
    mae_pct: Decimal,
    net_pnl_usd: Decimal,
    exit_reason: str,
    initial_risk_usd: Decimal = Decimal("1.50")
) -> str:
    """
    Empirical taxonomy diagnosing the structural mechanism of trade outcome.
    
    Goldmine Autopsy Categories:
    - WIN_SQUEEZE: Hit take-profit or locked profit via dynamic ratchet.
    - STALL_SCRATCH: Stalled for 12m without expansion, scratched near breakeven.
    - ZERO_MFE_LIQ_FLUSH: MFE == 0.00%. Immediate stop-out from liquidity sweep.
    - MFE_REVERSAL: Traveled >= +0.50% towards target but collapsed to stop.
    - STEAMROLLER_OUTLIER: Loss exceeded 1.5x initial risk ($2.25+) due to slippage/gap.
    - STOP_OUT: Normal expected stop-out within controlled risk envelope.
    """
    if is_win:
        return "WIN_SQUEEZE"
    if exit_reason in ("STALL_SCRATCH", "RATCHET_BE") and net_pnl_usd >= Decimal("-0.20"):
        return "STALL_SCRATCH"
    if abs(net_pnl_usd) > initial_risk_usd * Decimal("1.5"):
        return "STEAMROLLER_OUTLIER"
    if mfe_pct == Decimal("0"):
        return "ZERO_MFE_LIQ_FLUSH"
    if mfe_pct >= Decimal("0.0050"):
        return "MFE_REVERSAL"
    return "STOP_OUT"


@dataclass
class TigerTradeForensics:
    """Full forensic telemetry record for a single closed Tiger trade."""
    trade_id: str
    symbol: str
    side: str                          # "BUY" or "SELL"
    entry_price: Decimal
    exit_price: Decimal
    notional_usd: Decimal
    net_pnl_usd: Decimal
    net_pnl_pct: Decimal
    duration_seconds: int
    exit_reason: str                   # "TAKE_PROFIT", "STOP_LOSS", "RATCHET_BE", "STALL_SCRATCH", "HARD_KILL"
    is_win: bool
    mfe_pct: Decimal                   # Maximum Favorable Excursion
    mae_pct: Decimal                   # Maximum Adverse Excursion
    wick_ratio: Decimal                # Absorption wick ratio at entry
    cvd_zscore: Decimal                # CVD delta z-score at entry
    is_slow_regime: bool
    created_at_utc: str
    closed_at_utc: str
    execution_mode: str = "PAPER"      # "PAPER" or "LIVE"
    autopsy_code: str = "NORMAL"       # Diagnostic code


@dataclass
class TigerDistilledRules:
    """Active distilled rules generated by the autonomous learning engine."""
    audit_id: str
    updated_at_utc: str
    sample_size: int
    win_rate_pct: Decimal
    profit_factor: Decimal
    avg_mfe_pct: Decimal
    avg_mae_pct: Decimal
    calibrated_min_wick_ratio: Decimal
    calibrated_min_cvd_zscore: Decimal
    calibrated_slow_tp_pct: Decimal
    calibrated_slow_sl_pct: Decimal
    quarantined_symbols: List[str]
    best_performing_symbols: List[str]
    paper_sample_size: int = 0
    live_sample_size: int = 0
    paper_win_rate_pct: Decimal = Decimal("0.0")
    live_win_rate_pct: Decimal = Decimal("0.0")
    quarantine_registry: Dict[str, Dict[str, Any]] = field(default_factory=dict)
    autopsy_breakdown: Dict[str, int] = field(default_factory=dict)


class TigerLearningEngine:
    """
    Forensics and Self-Learning Engine for Strategy #3 (Stalking Tiger).
    Supports Dual-Track Bayesian Calibration, Autopsy Tagging, and Temporal Quarantine Graduation.
    """
    def __init__(
        self,
        db_path: str = DEFAULT_TIGER_DB,
        rules_path: str = DEFAULT_TIGER_RULES
    ):
        self.db_path = db_path
        self.rules_path = rules_path
        self._init_db()

    def _init_db(self) -> None:
        """Initialize SQLite database for trade forensics, quarantines, and shadow evals."""
        os.makedirs(os.path.dirname(self.db_path), exist_ok=True)
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS tiger_trades (
                    trade_id TEXT PRIMARY KEY,
                    symbol TEXT NOT NULL,
                    side TEXT NOT NULL,
                    entry_price TEXT NOT NULL,
                    exit_price TEXT NOT NULL,
                    notional_usd TEXT NOT NULL,
                    net_pnl_usd TEXT NOT NULL,
                    net_pnl_pct TEXT NOT NULL,
                    duration_seconds INTEGER NOT NULL,
                    exit_reason TEXT NOT NULL,
                    is_win INTEGER NOT NULL,
                    mfe_pct TEXT NOT NULL,
                    mae_pct TEXT NOT NULL,
                    wick_ratio TEXT NOT NULL,
                    cvd_zscore TEXT NOT NULL,
                    is_slow_regime INTEGER NOT NULL,
                    created_at_utc TEXT NOT NULL,
                    closed_at_utc TEXT NOT NULL,
                    execution_mode TEXT NOT NULL DEFAULT 'PAPER',
                    autopsy_code TEXT NOT NULL DEFAULT 'NORMAL'
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS tiger_audits (
                    audit_id TEXT PRIMARY KEY,
                    timestamp_utc TEXT NOT NULL,
                    sample_size INTEGER NOT NULL,
                    win_rate_pct TEXT NOT NULL,
                    profit_factor TEXT NOT NULL,
                    avg_mfe_pct TEXT NOT NULL,
                    calibrated_rules TEXT NOT NULL
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS tiger_quarantines (
                    symbol TEXT PRIMARY KEY,
                    quarantined_at_utc TEXT NOT NULL,
                    expiry_utc TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    strike_count INTEGER NOT NULL,
                    execution_mode TEXT NOT NULL,
                    status TEXT NOT NULL
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS tiger_shadow_evals (
                    eval_id INTEGER PRIMARY KEY AUTOINCREMENT,
                    symbol TEXT NOT NULL,
                    timestamp_utc TEXT NOT NULL,
                    is_win INTEGER NOT NULL,
                    mfe_pct TEXT NOT NULL
                )
            """)

            # Run backward-compatibility migrations
            try:
                cursor.execute("ALTER TABLE tiger_trades ADD COLUMN execution_mode TEXT DEFAULT 'PAPER'")
            except Exception:
                pass
            try:
                cursor.execute("ALTER TABLE tiger_trades ADD COLUMN autopsy_code TEXT DEFAULT 'NORMAL'")
            except Exception:
                pass

            # Retroactive autopsy backfill for unclassified historical trades
            try:
                cursor.execute("""
                    SELECT trade_id, is_win, mfe_pct, mae_pct, net_pnl_usd, exit_reason
                    FROM tiger_trades
                    WHERE autopsy_code = 'NORMAL' OR autopsy_code IS NULL
                """)
                unclassified = cursor.fetchall()
                for row in unclassified:
                    tid, win_i, mfe_s, mae_s, pnl_s, rsn = row
                    auto_code = classify_trade_autopsy(
                        is_win=bool(win_i),
                        mfe_pct=Decimal(mfe_s),
                        mae_pct=Decimal(mae_s),
                        net_pnl_usd=Decimal(pnl_s),
                        exit_reason=rsn
                    )
                    cursor.execute("UPDATE tiger_trades SET autopsy_code = ? WHERE trade_id = ?", (auto_code, tid))
            except Exception as e:
                logger.warning(f"[DB INIT] Backfill warning: {e}")

            conn.commit()

    def record_trade(self, trade: TigerTradeForensics) -> None:
        """Persist a closed trade forensic record with dual-track and autopsy tags."""
        # Auto-classify autopsy if default
        if trade.autopsy_code == "NORMAL":
            trade.autopsy_code = classify_trade_autopsy(
                is_win=trade.is_win,
                mfe_pct=trade.mfe_pct,
                mae_pct=trade.mae_pct,
                net_pnl_usd=trade.net_pnl_usd,
                exit_reason=trade.exit_reason
            )

        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT OR REPLACE INTO tiger_trades VALUES (
                    ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
                )
            """, (
                trade.trade_id, trade.symbol, trade.side, str(trade.entry_price),
                str(trade.exit_price), str(trade.notional_usd), str(trade.net_pnl_usd),
                str(trade.net_pnl_pct), trade.duration_seconds, trade.exit_reason,
                1 if trade.is_win else 0, str(trade.mfe_pct), str(trade.mae_pct),
                str(trade.wick_ratio), str(trade.cvd_zscore),
                1 if trade.is_slow_regime else 0, trade.created_at_utc, trade.closed_at_utc,
                trade.execution_mode, trade.autopsy_code
            ))
            conn.commit()
        logger.info(
            f"[TIGER FORENSICS] Recorded {trade.execution_mode} trade {trade.trade_id} "
            f"({trade.symbol} {trade.exit_reason} -> {trade.autopsy_code}) | PnL: ${trade.net_pnl_usd}"
        )

    def fetch_all_trades(self, limit: int = 500) -> List[TigerTradeForensics]:
        """Fetch historical trades for audit."""
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                SELECT trade_id, symbol, side, entry_price, exit_price, notional_usd,
                       net_pnl_usd, net_pnl_pct, duration_seconds, exit_reason, is_win,
                       mfe_pct, mae_pct, wick_ratio, cvd_zscore, is_slow_regime,
                       created_at_utc, closed_at_utc, execution_mode, autopsy_code
                FROM tiger_trades ORDER BY rowid DESC LIMIT ?
            """, (limit,))
            rows = cursor.fetchall()

        records = []
        for r in rows:
            exec_mode = r[18] if len(r) > 18 and r[18] else "PAPER"
            auto_code = r[19] if len(r) > 19 and r[19] else "NORMAL"
            records.append(TigerTradeForensics(
                trade_id=r[0], symbol=r[1], side=r[2], entry_price=Decimal(r[3]),
                exit_price=Decimal(r[4]), notional_usd=Decimal(r[5]), net_pnl_usd=Decimal(r[6]),
                net_pnl_pct=Decimal(r[7]), duration_seconds=r[8], exit_reason=r[9],
                is_win=bool(r[10]), mfe_pct=Decimal(r[11]), mae_pct=Decimal(r[12]),
                wick_ratio=Decimal(r[13]), cvd_zscore=Decimal(r[14]),
                is_slow_regime=bool(r[15]), created_at_utc=r[16], closed_at_utc=r[17],
                execution_mode=exec_mode, autopsy_code=auto_code
            ))
        return records

    def quarantine_symbol(
        self,
        symbol: str,
        reason: str,
        execution_mode: str = "PAPER",
        duration_hours: int = 12,
        strike_count: int = 1,
        now_dt: Optional[datetime.datetime] = None
    ) -> None:
        """Places a symbol into quarantine with an explicit temporal expiration."""
        now = now_dt or datetime.datetime.now(datetime.timezone.utc)
        expiry = now + datetime.timedelta(hours=duration_hours)
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT OR REPLACE INTO tiger_quarantines VALUES (?, ?, ?, ?, ?, ?, 'ACTIVE')
            """, (
                symbol, now.isoformat(), expiry.isoformat(),
                reason, strike_count, execution_mode
            ))
            conn.commit()
        logger.warning(
            f"[QUARANTINE ENFORCED] Symbol {symbol} quarantined for {duration_hours}h "
            f"(Mode: {execution_mode}, Reason: {reason}) until {expiry.isoformat()}"
        )

    def graduate_symbol(self, symbol: str, reason: str = "EXPIRY_GRADUATION") -> None:
        """Graduates a symbol out of quarantine."""
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                UPDATE tiger_quarantines SET status = 'GRADUATED' WHERE symbol = ?
            """, (symbol,))
            conn.commit()
        logger.info(f"[QUARANTINE GRADUATED] Symbol {symbol} graduated ({reason}) and returned to active hunting.")

    def record_shadow_signal(self, symbol: str, is_win: bool, mfe_pct: Decimal, now_dt: Optional[datetime.datetime] = None) -> None:
        """Records a shadow evaluation for a quarantined symbol to evaluate potential re-qualification."""
        now = now_dt or datetime.datetime.now(datetime.timezone.utc)
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT INTO tiger_shadow_evals (symbol, timestamp_utc, is_win, mfe_pct)
                VALUES (?, ?, ?, ?)
            """, (symbol, now.isoformat(), 1 if is_win else 0, str(mfe_pct)))
            conn.commit()

    def evaluate_quarantines(self, now_dt: Optional[datetime.datetime] = None) -> Tuple[List[str], Dict[str, Dict[str, Any]]]:
        """
        Audits active quarantines against temporal decay and shadow performance.
        Returns: (active_quarantined_symbols, full_quarantine_registry)
        """
        now = now_dt or datetime.datetime.now(datetime.timezone.utc)
        active_symbols: List[str] = []
        registry: Dict[str, Dict[str, Any]] = {}

        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT symbol, quarantined_at_utc, expiry_utc, reason, strike_count, execution_mode, status FROM tiger_quarantines")
            rows = cursor.fetchall()

            for r in rows:
                sym, q_at_s, exp_s, rsn, strikes, mode, status = r
                exp_dt = datetime.datetime.fromisoformat(exp_s)
                q_dt = datetime.datetime.fromisoformat(q_at_s)

                if status == "ACTIVE":
                    # 1. Temporal Expiration Check (Decay)
                    if now >= exp_dt:
                        cursor.execute("UPDATE tiger_quarantines SET status = 'GRADUATED' WHERE symbol = ?", (sym,))
                        logger.info(f"[QUARANTINE EXPIRED] {sym} quarantine expired after elapsed time. Auto-graduated.")
                        status = "GRADUATED"
                    else:
                        # 2. Shadow Re-qualification Check (>= 3 shadow signals with >= 66% win rate)
                        cursor.execute("""
                            SELECT is_win FROM tiger_shadow_evals
                            WHERE symbol = ? AND timestamp_utc >= ?
                            ORDER BY eval_id DESC LIMIT 5
                        """, (sym, q_at_s))
                        shadow_rows = cursor.fetchall()
                        if len(shadow_rows) >= 3:
                            shadow_wins = sum(1 for sr in shadow_rows if sr[0] == 1)
                            shadow_wr = Decimal(str(shadow_wins)) / Decimal(str(len(shadow_rows)))
                            if shadow_wr >= Decimal("0.66"):
                                cursor.execute("UPDATE tiger_quarantines SET status = 'GRADUATED' WHERE symbol = ?", (sym,))
                                logger.info(f"[SHADOW REQUALIFICATION] {sym} achieved {shadow_wr*100:.1f}% shadow win rate ({shadow_wins}/{len(shadow_rows)}). Early graduation granted!")
                                status = "GRADUATED"

                registry[sym] = {
                    "symbol": sym,
                    "quarantined_at_utc": q_at_s,
                    "expiry_utc": exp_s,
                    "reason": rsn,
                    "strike_count": strikes,
                    "execution_mode": mode,
                    "status": status
                }
                if status == "ACTIVE":
                    active_symbols.append(sym)

            conn.commit()

        return active_symbols, registry

    def run_learning_distillation(self, now_dt: Optional[datetime.datetime] = None) -> Optional[TigerDistilledRules]:
        """
        Runs autonomous distillation audit across all recorded trades with Dual-Track Bayesian Weighting.
        Discovers symbol expectancies, optimal wick thresholds, and recalibrates brackets.
        """
        now = now_dt or datetime.datetime.now(datetime.timezone.utc)
        now_utc = now.isoformat()
        trades = self.fetch_all_trades(limit=200)
        if not trades:
            return None

        total_trades = len(trades)
        wins = [t for t in trades if t.is_win]
        losses = [t for t in trades if not t.is_win]
        win_wicks = [t.wick_ratio for t in wins]

        # Separate Dual-Track Subsets
        paper_trades = [t for t in trades if t.execution_mode == "PAPER"]
        live_trades = [t for t in trades if t.execution_mode == "LIVE"]
        paper_wins = [t for t in paper_trades if t.is_win]
        live_wins = [t for t in live_trades if t.is_win]

        paper_wr = (Decimal(str(len(paper_wins))) / Decimal(str(len(paper_trades))) * Decimal("100")) if paper_trades else Decimal("0.0")
        live_wr = (Decimal(str(len(live_wins))) / Decimal(str(len(live_trades))) * Decimal("100")) if live_trades else Decimal("0.0")

        # Bayesian Authority Weighting: Live trades carry 3.0x weight, Paper trades carry 1.0x weight
        w_paper = Decimal("1.0")
        w_live = Decimal("3.0")
        weighted_wins = (Decimal(str(len(paper_wins))) * w_paper) + (Decimal(str(len(live_wins))) * w_live)
        weighted_total = (Decimal(str(len(paper_trades))) * w_paper) + (Decimal(str(len(live_trades))) * w_live)
        effective_win_rate = (weighted_wins / weighted_total * Decimal("100")) if weighted_total > Decimal("0") else Decimal("0.0")

        gross_win_usd = sum(t.net_pnl_usd for t in wins)
        gross_loss_usd = abs(sum(t.net_pnl_usd for t in losses))
        profit_factor = (gross_win_usd / gross_loss_usd) if gross_loss_usd > Decimal("0") else Decimal("99.99")

        avg_mfe = sum(t.mfe_pct for t in trades) / Decimal(str(total_trades))
        avg_mae = sum(t.mae_pct for t in trades) / Decimal(str(total_trades))

        # Forensic Autopsy Breakdown
        autopsy_counts: Dict[str, int] = {}
        for t in trades:
            autopsy_counts[t.autopsy_code] = autopsy_counts.get(t.autopsy_code, 0) + 1

        # Symbol Expectancy & Quarantine Assessment (Rolling 24h Window)
        lookback_24h = now - datetime.timedelta(hours=24)
        recent_trades = [
            t for t in trades
            if datetime.datetime.fromisoformat(t.closed_at_utc.replace("Z", "+00:00")) >= lookback_24h
        ]
        sym_perf: Dict[str, List[Decimal]] = {}
        sym_losses: Dict[str, int] = {}
        sym_live_losses: Dict[str, int] = {}

        for t in recent_trades:
            sym_perf.setdefault(t.symbol, []).append(t.net_pnl_usd)
            if not t.is_win:
                sym_losses[t.symbol] = sym_losses.get(t.symbol, 0) + 1
                if t.execution_mode == "LIVE":
                    sym_live_losses[t.symbol] = sym_live_losses.get(t.symbol, 0) + 1

        best_symbols = []
        for sym, pnls in sym_perf.items():
            tot_pnl = sum(pnls)
            # Live Loss Quarantine Rule: 1 live trade loss triggers immediate 24h quarantine
            if sym_live_losses.get(sym, 0) >= 1:
                self.quarantine_symbol(
                    symbol=sym,
                    reason="LIVE_LOSS_QUARANTINE",
                    execution_mode="LIVE",
                    duration_hours=24,
                    strike_count=sym_live_losses[sym],
                    now_dt=now
                )
            # Paper Loss Quarantine Rule: >= 2 paper losses or net loss <= -$1.00 in 24h triggers 12h quarantine
            elif sym_losses.get(sym, 0) >= 2 or tot_pnl <= Decimal("-1.00"):
                self.quarantine_symbol(
                    symbol=sym,
                    reason="PAPER_TOXIC_STREAK",
                    execution_mode="PAPER",
                    duration_hours=12,
                    strike_count=sym_losses.get(sym, 0),
                    now_dt=now
                )
            elif tot_pnl > Decimal("0.50"):
                best_symbols.append(sym)

        # Audit Active Quarantines (checks for temporal decay and shadow graduation)
        active_quarantined, quarantine_registry = self.evaluate_quarantines(now_dt=now)

        # Dynamic Wick Ratio Adaptation based on Effective Win Rate:
        calibrated_wick = Decimal("0.40")
        if effective_win_rate < Decimal("50.0") and total_trades >= 2:
            calibrated_wick = Decimal("0.48")
        elif effective_win_rate >= Decimal("70.0"):
            calibrated_wick = Decimal("0.42")
        elif win_wicks:
            avg_win_wick = sum(win_wicks) / Decimal(str(len(win_wicks)))
            if avg_win_wick > Decimal("0.45"):
                calibrated_wick = Decimal("0.45")

        # Dynamic CVD Z-score Adaptation:
        calibrated_cvd_z = Decimal("2.0")
        if effective_win_rate < Decimal("50.0") and total_trades >= 2:
            calibrated_cvd_z = Decimal("2.4")

        # Dynamic TP/SL Adaptation based on MFE
        calibrated_slow_tp = Decimal("0.0101")
        calibrated_slow_sl = Decimal("0.0066")
        if avg_mfe > Decimal("0") and avg_mfe < Decimal("0.0080") and total_trades >= 3:
            calibrated_slow_tp = Decimal("0.0080")
            calibrated_slow_sl = Decimal("0.0055")

        audit_id = f"TIGER_AUDIT_{int(now.timestamp())}"

        distilled = TigerDistilledRules(
            audit_id=audit_id,
            updated_at_utc=now_utc,
            sample_size=total_trades,
            win_rate_pct=effective_win_rate.quantize(Decimal("0.1")),
            profit_factor=profit_factor.quantize(Decimal("0.01")),
            avg_mfe_pct=avg_mfe.quantize(Decimal("0.0001")),
            avg_mae_pct=avg_mae.quantize(Decimal("0.0001")),
            calibrated_min_wick_ratio=calibrated_wick,
            calibrated_min_cvd_zscore=calibrated_cvd_z,
            calibrated_slow_tp_pct=calibrated_slow_tp,
            calibrated_slow_sl_pct=calibrated_slow_sl,
            quarantined_symbols=active_quarantined,
            best_performing_symbols=best_symbols,
            paper_sample_size=len(paper_trades),
            live_sample_size=len(live_trades),
            paper_win_rate_pct=paper_wr.quantize(Decimal("0.1")),
            live_win_rate_pct=live_wr.quantize(Decimal("0.1")),
            quarantine_registry=quarantine_registry,
            autopsy_breakdown=autopsy_counts
        )

        # Save to disk
        os.makedirs(os.path.dirname(self.rules_path), exist_ok=True)
        with open(self.rules_path, "w", encoding="utf-8") as f:
            data = {
                "audit_id": distilled.audit_id,
                "updated_at_utc": distilled.updated_at_utc,
                "sample_size": distilled.sample_size,
                "win_rate_pct": str(distilled.win_rate_pct),
                "profit_factor": str(distilled.profit_factor),
                "avg_mfe_pct": str(distilled.avg_mfe_pct),
                "avg_mae_pct": str(distilled.avg_mae_pct),
                "calibrated_min_wick_ratio": str(distilled.calibrated_min_wick_ratio),
                "calibrated_min_cvd_zscore": str(distilled.calibrated_min_cvd_zscore),
                "calibrated_slow_tp_pct": str(distilled.calibrated_slow_tp_pct),
                "calibrated_slow_sl_pct": str(distilled.calibrated_slow_sl_pct),
                "quarantined_symbols": distilled.quarantined_symbols,
                "best_performing_symbols": distilled.best_performing_symbols,
                "paper_sample_size": distilled.paper_sample_size,
                "live_sample_size": distilled.live_sample_size,
                "paper_win_rate_pct": str(distilled.paper_win_rate_pct),
                "live_win_rate_pct": str(distilled.live_win_rate_pct),
                "quarantine_registry": distilled.quarantine_registry,
                "autopsy_breakdown": distilled.autopsy_breakdown
            }
            json.dump(data, f, indent=2)

        # Persist audit record in DB
        with sqlite3.connect(self.db_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT OR REPLACE INTO tiger_audits VALUES (?, ?, ?, ?, ?, ?, ?)
            """, (
                audit_id, now_utc, total_trades, str(effective_win_rate), str(profit_factor),
                str(avg_mfe), json.dumps(data)
            ))
            conn.commit()

        logger.info(
            f"[TIGER DISTILLATION] Audit {audit_id} complete ({total_trades} trades | Paper:{len(paper_trades)} Live:{len(live_trades)}): "
            f"Effective WR={distilled.win_rate_pct}% (Paper:{distilled.paper_win_rate_pct}% Live:{distilled.live_win_rate_pct}%) | "
            f"PF={distilled.profit_factor} | Quarantined={active_quarantined} | Autopsies={distilled.autopsy_breakdown}"
        )
        return distilled

    def load_distilled_rules(self) -> Optional[TigerDistilledRules]:
        """Loads and parses active distilled rules from disk for dynamic execution."""
        if not os.path.exists(self.rules_path):
            return None
        try:
            with open(self.rules_path, "r", encoding="utf-8") as f:
                d = json.load(f)
            return TigerDistilledRules(
                audit_id=d.get("audit_id", ""),
                updated_at_utc=d.get("updated_at_utc", ""),
                sample_size=int(d.get("sample_size", 0)),
                win_rate_pct=Decimal(str(d.get("win_rate_pct", "0.0"))),
                profit_factor=Decimal(str(d.get("profit_factor", "0.0"))),
                avg_mfe_pct=Decimal(str(d.get("avg_mfe_pct", "0.0"))),
                avg_mae_pct=Decimal(str(d.get("avg_mae_pct", "0.0"))),
                calibrated_min_wick_ratio=Decimal(str(d.get("calibrated_min_wick_ratio", "0.40"))),
                calibrated_min_cvd_zscore=Decimal(str(d.get("calibrated_min_cvd_zscore", "2.0"))),
                calibrated_slow_tp_pct=Decimal(str(d.get("calibrated_slow_tp_pct", "0.0101"))),
                calibrated_slow_sl_pct=Decimal(str(d.get("calibrated_slow_sl_pct", "0.0066"))),
                quarantined_symbols=list(d.get("quarantined_symbols", [])),
                best_performing_symbols=list(d.get("best_performing_symbols", [])),
                paper_sample_size=int(d.get("paper_sample_size", 0)),
                live_sample_size=int(d.get("live_sample_size", 0)),
                paper_win_rate_pct=Decimal(str(d.get("paper_win_rate_pct", "0.0"))),
                live_win_rate_pct=Decimal(str(d.get("live_win_rate_pct", "0.0"))),
                quarantine_registry=dict(d.get("quarantine_registry", {})),
                autopsy_breakdown=dict(d.get("autopsy_breakdown", {}))
            )
        except Exception as e:
            logger.error(f"[TIGER LEARNING] Failed to load distilled rules: {e}")
            return None
