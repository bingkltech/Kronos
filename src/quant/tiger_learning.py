"""
src/quant/tiger_learning.py — Real-Time Forensics & Dual-Track Bayesian Self-Learning Distillation Engine.

Persists every trade to SQLite (data/tiger_trades.db) with sub-second telemetry:
MFE (Peak Favorable Excursion), MAE (Adverse Drawdown), Absorption Wick Ratio, CVD Z-score,
and exit reasons (TP, SL, Velocity Ratchet, Stall Scratch, Hard Kill).

Features the Kronos Dual-Track Architecture:
1. Dual-Track Execution Modes: "PAPER" (Exploratory sandbox) vs "LIVE" (Real-money authority).
2. Forensic Autopsy Taxonomy: Classifies outcomes into WIN_SQUEEZE, ZERO_MFE_LIQ_FLUSH,
   STALL_SCRATCH, MFE_REVERSAL, STEAMROLLER_OUTLIER, and STOP_OUT.
3. Bayesian Authority Weighting: Live trades carry 3x statistical weight over paper trades in rule distillation.
4. Shadow Re-qualification & Temporal Quarantine Decay: Quarantines expire automatically after 12h (paper)
   or 24h (live), or graduate early via shadow paper qualification (>= 66% win rate over 3 evals).
5. Strategy-Regime Segregation: Prevents mean-reversion stops from contaminating trend-following fleets.

Strictly enforces AGENTS.md Invariant 1 (Zero Float Financial Math with Decimal).
"""

