# -*- coding: utf-8 -*-
"""
Gemini Meta-Strategy Arbiter & Hyperparameter Governor.

Provides slow-cadence, high-level supervisory portfolio review using the Google
Gemini Free Tier API (gemini-3.8-flash via google-genai). Dynamically identifies the
"sweetspot" parameters for KEV.ai, Kronos ONNX, and the Learning Governor based on
empirical win/loss outcomes, Brier loss scores, and macro regime breadth.
"""

import json
import logging
import os
from decimal import Decimal
from typing import Any, Dict, List, Optional
from datetime import datetime, timezone
from dataclasses import dataclass, asdict
from dotenv import load_dotenv

logger = logging.getLogger("kronos.quant.gemini_arbiter")

# Load environment variables from .env
env_path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), ".env")
if os.path.exists(env_path):
    load_dotenv(dotenv_path=env_path)
else:
    load_dotenv()


# ==============================================================================
# Quantitative Parameter Safety Bounds (Hard Invariants)
# ==============================================================================

MIN_RR_BOUND = Decimal("1.40")
MAX_RR_BOUND = Decimal("2.20")

MIN_FEE_HURDLE_BOUND = Decimal("0.0035")  # 0.35%
MAX_FEE_HURDLE_BOUND = Decimal("0.0075")  # 0.75%

MIN_RISK_BUDGET_BOUND = Decimal("0.008")  # 0.8%
MAX_RISK_BUDGET_BOUND = Decimal("0.015")  # 1.5% (Max $3.00 on $200 equity)

MIN_FAST_EMA_BOUND = 8
MAX_FAST_EMA_BOUND = 25

MIN_SLOW_EMA_BOUND = 40
MAX_SLOW_EMA_BOUND = 90


@dataclass
class StrategyAssessmentOutput:
    """Structured assessment generated by Gemini Meta-Strategist."""
    regime_diagnosis: str
    sweetspot_rr_ratio: float
    sweetspot_fee_hurdle_pct: float
    sweetspot_risk_budget_pct: float
    sweetspot_fast_ema: int
    sweetspot_slow_ema: int
    market_edge_summary: str
    confidence_score: float
    action_items: List[str]
    timestamp: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class GeminiStrategyArbiter:
    """
    Supervisory meta-strategy governor integrating Google Gemini Free Tier.
    Acts as the Chief Investment Officer to tune parameters for maximum expectancy.
    """

    def __init__(self, api_key: Optional[str] = None, model_name: str = "gemini-3.8-flash"):
        self.api_key = api_key if api_key is not None else os.getenv("GEMINI_API_KEY", "")
        self.model_name = model_name
        self.client = None
        self._init_client()

    def _init_client(self):
        """Initialize Google GenAI client if API key is present."""
        if not self.api_key:
            logger.info("GEMINI_API_KEY not found. GeminiStrategyArbiter running in fallback mode.")
            return

        try:
            from google import genai
            self.client = genai.Client(api_key=self.api_key)
            logger.info(f"GeminiStrategyArbiter initialized successfully with model {self.model_name}")
        except Exception as e:
            logger.warning(f"Failed to initialize google-genai client: {e}")
            self.client = None

    def is_available(self) -> bool:
        """Return True if Gemini API client is initialized and ready."""
        return self.client is not None and bool(self.api_key)

    def build_strategic_digest(
        self,
        macro_summary: Dict[str, Any],
        paper_summary: Dict[str, Any],
        lessons_summary: Dict[str, Any],
        current_settings: Dict[str, Any]
    ) -> str:
        """
        Construct a concise, high-density quantitative markdown digest (< 1,200 tokens).
        Zero token bloat: omits massive raw candle arrays while providing high-signal metrics.
        """
        closed_trades = paper_summary.get("closed_trades", [])
        last_5_trades = closed_trades[-5:] if closed_trades else []

        trades_repr = []
        for t in last_5_trades:
            trades_repr.append(
                f"- [{t.get('symbol', 'BTCUSDT')} {t.get('side', 'LONG')}] "
                f"Entry: {t.get('entry_price', 0)} | Exit: {t.get('exit_price', 0)} | "
                f"PnL: {t.get('pnl_usd', 0):.2f} USDT ({t.get('pnl_pct', 0):.2f}%) | "
                f"Reason: {t.get('exit_reason', 'N/A')}"
            )
        trades_text = "\n".join(trades_repr) if trades_repr else "No closed trades recorded yet."

        digest = f"""# KRONOS SYSTEMIC PERFORMANCE DIGEST FOR STRATEGIC ASSESSMENT

## 1. Macro Regime & Systemic Breadth
- Macro Regime: {macro_summary.get('macro_regime', 'CHOP_COMPRESSION')}
- Top-10 Composite Breadth: {macro_summary.get('breadth_pct', '50.0%')} ({macro_summary.get('coins_above_vwap', 0)} / {macro_summary.get('total_coins', 10)} coins above 24h VWAP)
- High-Impact News Blackout: {'ACTIVE - DO NOT TRADE' if macro_summary.get('news_blackout', {}).get('is_blackout') else 'CLEAR'}

## 2. Small-Account Paper Trading Performance ($200.00 USDT Baseline)
- Account Equity: {paper_summary.get('current_equity_usdt', 200.0):.2f} USDT
- Total Completed Trades: {paper_summary.get('total_trades', 0)} (Wins: {paper_summary.get('wins', 0)}, Losses: {paper_summary.get('losses', 0)})
- Win Rate: {paper_summary.get('win_rate_pct', 0.0):.1f}%
- Net Realized PnL: {paper_summary.get('net_pnl_usdt', 0.0):.2f} USDT ({paper_summary.get('net_pnl_pct', 0.0):.2f}%)
- Profit Factor: {paper_summary.get('profit_factor', 1.0):.2f}

## 3. Recent Trade Outlines (Last 5)
{trades_text}

## 4. Bayesian Learning & Calibration
- Rolling 48h Brier Score: {lessons_summary.get('brier_score', 0.20):.4f} (Target: < 0.20 for 1.0x allocation)
- Capital Multiplier: {lessons_summary.get('confidence_multiplier', 1.0):.2f}x
- Total Post-Mortems in Lessons DB: {lessons_summary.get('total_lessons', 0)}

## 5. Active Parameter Configuration
- Target Reward/Risk (R:R) Hurdle: {current_settings.get('rr_hurdle_ratio', 1.60):.2f}:1
- Net Expected Fee Hurdle: {current_settings.get('fee_hurdle_pct', 0.50):.2f}%
- Base Dollar Risk Budget: {current_settings.get('risk_budget_pct', 1.5):.2f}% (Max $3.00 on $200 USDT account)
- 3D Sweep Optimal Coordinate: Fast EMA {current_settings.get('param_sweep_fast_ema', 17)} / Slow EMA {current_settings.get('param_sweep_slow_ema', 65)}

---
MANDATE AS CHIEF QUANTITATIVE STRATEGIST:
Diagnose whether the current hyperparameters are in the optimal 'sweetspot'. If trades are being stopped out prematurely, widen the ATR buffer or adjust R:R. If market is in Chop Compression, recommend tighter profit taking. Return structured JSON recommendations within safe quantitative bounds.
"""
        return digest

    def evaluate_strategy(
        self,
        macro_summary: Dict[str, Any],
        paper_summary: Dict[str, Any],
        lessons_summary: Dict[str, Any],
        current_settings: Optional[Dict[str, Any]] = None
    ) -> StrategyAssessmentOutput:
        """
        Execute strategic meta-assessment via Gemini API Free Tier (or deterministic fallback).
        Applies mathematical safety clamping to prevent hallucinated or runaway settings.
        """
        curr = current_settings or {
            "rr_hurdle_ratio": 1.60,
            "fee_hurdle_pct": 0.50,
            "risk_budget_pct": 1.50,
            "param_sweep_fast_ema": 17,
            "param_sweep_slow_ema": 65
        }

        if not self.is_available():
            logger.info("Gemini API not available. Generating deterministic quantitative assessment.")
            return self._generate_fallback_assessment(macro_summary, paper_summary, curr)

        digest = self.build_strategic_digest(macro_summary, paper_summary, lessons_summary, curr)

        prompt = f"""You are the Senior Chief Quantitative Strategist for Kronos Algorithmic Trading Systems.
Analyze the following systemic performance digest and output your strategic assessment as JSON conforming to the following structure:
{{
  "regime_diagnosis": "<Short narrative diagnosis of current market regime and volatility state>",
  "sweetspot_rr_ratio": <float between 1.40 and 2.20 representing optimal target R:R ratio>,
  "sweetspot_fee_hurdle_pct": <float between 0.35 and 0.70 representing minimum expected edge hurdle %>,
  "sweetspot_risk_budget_pct": <float between 0.8 and 1.5 representing max equity risk % per trade>,
  "sweetspot_fast_ema": <integer between 8 and 25 for fast trend window>,
  "sweetspot_slow_ema": <integer between 40 and 90 for slow trend window>,
  "market_edge_summary": "<2-3 sentence executive rationale on how these settings capture the sweetspot and eliminate loss friction>",
  "confidence_score": <float between 0.50 and 0.99 indicating confidence in recommendation>,
  "action_items": ["<Bullet 1>", "<Bullet 2>", "<Bullet 3>"]
}}

{digest}
"""
        try:
            from google.genai import types

            response = self.client.models.generate_content(
                model=self.model_name,
                contents=prompt,
                config=types.GenerateContentConfig(
                    response_mime_type="application/json",
                    temperature=0.2,
                )
            )

            raw_text = response.text.strip()
            data = json.loads(raw_text)

            # Extract and clamp parameters within institutional safety bounds
            rr = self._clamp_decimal(Decimal(str(data.get("sweetspot_rr_ratio", 1.60))), MIN_RR_BOUND, MAX_RR_BOUND)
            fee = self._clamp_decimal(Decimal(str(data.get("sweetspot_fee_hurdle_pct", 0.50))) / Decimal("100"), MIN_FEE_HURDLE_BOUND, MAX_FEE_HURDLE_BOUND)
            risk = self._clamp_decimal(Decimal(str(data.get("sweetspot_risk_budget_pct", 1.50))) / Decimal("100"), MIN_RISK_BUDGET_BOUND, MAX_RISK_BUDGET_BOUND)

            fast_ema = int(max(MIN_FAST_EMA_BOUND, min(MAX_FAST_EMA_BOUND, data.get("sweetspot_fast_ema", 17))))
            slow_ema = int(max(MIN_SLOW_EMA_BOUND, min(MAX_SLOW_EMA_BOUND, data.get("sweetspot_slow_ema", 65))))

            assessment = StrategyAssessmentOutput(
                regime_diagnosis=str(data.get("regime_diagnosis", macro_summary.get("macro_regime", "CHOP_COMPRESSION"))),
                sweetspot_rr_ratio=float(rr),
                sweetspot_fee_hurdle_pct=float(fee * Decimal("100")),
                sweetspot_risk_budget_pct=float(risk * Decimal("100")),
                sweetspot_fast_ema=fast_ema,
                sweetspot_slow_ema=slow_ema,
                market_edge_summary=str(data.get("market_edge_summary", "Strategic parameters optimized for current systemic breadth.")),
                confidence_score=float(min(0.99, max(0.50, data.get("confidence_score", 0.85)))),
                action_items=list(data.get("action_items", ["Maintain strict bracket discipline", "Monitor funding carry", "Keep position size <= $3.00"])),
                timestamp=datetime.now(timezone.utc).isoformat()
            )

            logger.info(f"Gemini Strategic Assessment complete: R:R={assessment.sweetspot_rr_ratio:.2f}, Fee Hurdle={assessment.sweetspot_fee_hurdle_pct:.2f}%")
            return assessment

        except Exception as e:
            logger.error(f"Gemini Strategic Assessment call failed: {e}. Falling back to deterministic model.")
            return self._generate_fallback_assessment(macro_summary, paper_summary, curr)

    def _clamp_decimal(self, val: Decimal, min_val: Decimal, max_val: Decimal) -> Decimal:
        """Clamp Decimal within safety bounds."""
        return max(min_val, min(max_val, val))

    def _generate_fallback_assessment(
        self,
        macro_summary: Dict[str, Any],
        paper_summary: Dict[str, Any],
        curr: Dict[str, Any]
    ) -> StrategyAssessmentOutput:
        """Deterministic algorithmic sweetspot calculation when API is unavailable."""
        regime = macro_summary.get("macro_regime", "CHOP_COMPRESSION")
        win_rate = paper_summary.get("win_rate_pct", 50.0)

        if regime == "BULL_EXPANSION":
            rr = 1.75
            fee = 0.55
            risk = 1.50
            fast_ema, slow_ema = 15, 60
            diag = "BULL_EXPANSION with directional momentum. Favorable to trend-following long continuation."
            edge = "Trend expansion supports wider 1.75:1 R:R targets without premature profit taking."
        elif regime == "BEAR_DISTRIBUTION":
            rr = 1.70
            fee = 0.50
            risk = 1.20
            fast_ema, slow_ema = 14, 55
            diag = "BEAR_DISTRIBUTION across benchmark index. Short momentum prioritized."
            edge = "Downside momentum allows short brackets to capture continuation with 1.70:1 R:R."
        else:
            # Chop compression: tighter profit target, tighter fee hurdle
            rr = 1.50
            fee = 0.45
            risk = 1.00
            fast_ema, slow_ema = 18, 68
            diag = "CHOP_COMPRESSION regime. Mean reversion and range-bound volatility dominate."
            edge = "Reduced target R:R to 1.50:1 secures quick gains before mean reversion whipsaws open positions."

        return StrategyAssessmentOutput(
            regime_diagnosis=diag,
            sweetspot_rr_ratio=rr,
            sweetspot_fee_hurdle_pct=fee,
            sweetspot_risk_budget_pct=risk,
            sweetspot_fast_ema=fast_ema,
            sweetspot_slow_ema=slow_ema,
            market_edge_summary=edge,
            confidence_score=0.82,
            action_items=[
                f"Regime {regime}: Align orders strictly with composite breadth.",
                f"Cap risk budget to {risk:.1f}% (${risk * 2.0:.2f} max per trade).",
                f"Target sweetspot R:R hurdle of {rr:.2f}:1."
            ],
            timestamp=datetime.now(timezone.utc).isoformat()
        )
